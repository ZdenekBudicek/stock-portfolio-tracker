import { build, version as esbuildVersion } from 'esbuild';
import ts from 'typescript';
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const artifactDir = resolve(root, 'supabase/functions/agent/_lib');
const entry = 'src/lib/agentLib.ts';
const portable = path => relative(root, path).replaceAll('\\', '/');
const hash = text => createHash('sha256').update(text.replaceAll('\r\n', '\n')).digest('hex');
const banner = '// Generated by scripts/build-agent-lib.mjs. Do not edit.\n';
const buildConfig = { bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', charset: 'utf8', legalComments: 'none' };
const declarationConfig = { declaration: true, emitDeclarationOnly: true, module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler, target: ts.ScriptTarget.ES2022, resolveJsonModule: true,
  allowImportingTsExtensions: true, skipLibCheck: true, strict: false, types: [], baseUrl: root,
  paths: { '@/*': ['./src/*'] } };

function failDiagnostics(diagnostics) {
  const errors = diagnostics.filter(d => d.category === ts.DiagnosticCategory.Error);
  if (errors.length) throw new Error(ts.formatDiagnostics(errors, {
    getCurrentDirectory: () => root, getCanonicalFileName: f => f, getNewLine: () => '\n',
  }));
}

// TypeScript emits the declarations; namespaces preserve private names and avoid collisions
// when combining them into one standalone module, without another build dependency.
function declarations(overrides) {
  const host = ts.createCompilerHost(declarationConfig);
  const originalRead = host.readFile;
  host.readFile = path => overrides[portable(resolve(path))] ?? originalRead(path);
  const emitted = new Map();
  host.writeFile = (_file, text, _bom, _error, sources) => {
    if (sources?.length !== 1) throw new Error('Expected one source per declaration');
    emitted.set(resolve(sources[0].fileName), text);
  };
  const program = ts.createProgram([resolve(root, entry)], declarationConfig, host);
  failDiagnostics(ts.getPreEmitDiagnostics(program));
  failDiagnostics(program.emit().diagnostics);
  const checker = program.getTypeChecker();
  // The public profile is a structural union inferred from Zod. Materialize that union
  // from the checker, so consumers need neither Zod nor its private schema declarations.
  const profileFile = resolve(root, 'src/lib/tax/profile.ts');
  const profileSource = program.getSourceFile(profileFile);
  const profileSymbols = checker.getExportsOfModule(checker.getSymbolAtLocation(profileSource));
  const profileTypes = ['TaxProfile', 'FilingStatus', 'Country'].map(name => {
    const type = checker.getDeclaredTypeOfSymbol(profileSymbols.find(symbol => symbol.name === name));
    return `export type ${name} = ${checker.typeToString(type, profileSource, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias)};`;
  });
  emitted.set(profileFile, profileTypes.join('\n') + '\nexport type Profile<C extends Country> = Extract<TaxProfile, { residence: C }>;\n');
  const files = [...emitted.keys()].sort((a, b) => portable(a).localeCompare(portable(b), 'en'));
  const names = new Map(files.map((file, i) => [file, `M${i}`]));
  const target = (specifier, file) => {
    const found = ts.resolveModuleName(specifier, file, declarationConfig, host).resolvedModule;
    const resolved = found && resolve(found.resolvedFileName);
    if (!resolved || !names.has(resolved)) throw new Error(`Declaration dependency outside bundle: ${specifier}`);
    return resolved;
  };
  const exportsOf = (file, onlyTypes) => checker.getExportsOfModule(checker.getSymbolAtLocation(program.getSourceFile(file)))
    .filter(symbol => {
      const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
      return !onlyTypes || !!(resolved.flags & (ts.SymbolFlags.Type | ts.SymbolFlags.Namespace));
    }).map(symbol => symbol.name);
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, removeComments: false });
  const bodies = files.map(file => {
    const source = ts.createSourceFile(file + '.d.ts', emitted.get(file), ts.ScriptTarget.Latest, true);
    const localImports = new Map();
    const explicitExports = new Set(source.statements.filter(ts.isExportDeclaration)
      .flatMap(s => s.exportClause && ts.isNamedExports(s.exportClause) ? s.exportClause.elements.map(el => el.name.text) : []));
    const lines = source.statements.map(statement => {
      if (ts.isImportDeclaration(statement)) {
        const ns = names.get(target(statement.moduleSpecifier.text, file));
        const clause = statement.importClause;
        if (!clause) return '';
        if (clause.name) {
          if (clause.namedBindings) throw new Error(`Mixed declaration import in ${portable(file)}`);
          localImports.set(clause.name.text, `${ns}.DefaultExport`);
          return `import ${clause.name.text} = ${ns}.DefaultExport;`;
        }
        if (ts.isNamespaceImport(clause.namedBindings)) {
          localImports.set(clause.namedBindings.name.text, ns);
          return `import ${clause.namedBindings.name.text} = ${ns};`;
        }
        return clause.namedBindings.elements.map(el => {
          const alias = `${ns}.${el.propertyName?.text ?? el.name.text}`;
          localImports.set(el.name.text, alias);
          return `import ${el.name.text} = ${alias};`;
        }).join('\n');
      }
      if (ts.isExportDeclaration(statement)) {
        if (!statement.moduleSpecifier) {
          return statement.exportClause?.elements.map(el => {
            const name = el.propertyName?.text ?? el.name.text;
            if (name === el.name.text && !localImports.has(name)) return '';
            return `export import ${el.name.text} = ${localImports.get(name) ?? name};`;
          }).join('\n') ?? '';
        }
        const dependency = target(statement.moduleSpecifier.text, file), ns = names.get(dependency);
        if (dependency === profileFile && statement.exportClause && !statement.isTypeOnly) return '';
        if (statement.exportClause && !ts.isNamedExports(statement.exportClause)) throw new Error('Namespace re-export not supported');
        const elements = statement.exportClause?.elements.map(el => [el.name.text, el.propertyName?.text ?? el.name.text])
          ?? exportsOf(dependency, statement.isTypeOnly).filter(name => !explicitExports.has(name)).map(name => [name, name]);
        return elements.map(([name, original]) => `export import ${name} = ${ns}.${original};`).join('\n');
      }
      if (ts.isExportAssignment(statement)) {
        const name = statement.expression.getText(source);
        return localImports.has(name) ? `export import DefaultExport = ${localImports.get(name)};`
          : `export const DefaultExport: typeof ${name};`;
      }
      return printer.printNode(ts.EmitHint.Unspecified, statement, source).replace(/\bexport declare /g, 'export ')
        .replace(/import\("([^"]+)"\)\./g, (_match, specifier) => names.get(target(specifier, file)) + '.');
    });
    // Explicit runtime exports and type-star exports can refer to the same symbol.
    const aliases = new Set();
    const body = lines.flatMap(line => line.split('\n')).filter(line => {
      if (!line.startsWith('export import ')) return true;
      if (aliases.has(line)) return false;
      aliases.add(line); return true;
    });
    return `declare namespace ${names.get(file)} {\n${body.join('\n')}\n}`;
  });
  const publicNames = [...bodies[files.indexOf(resolve(root, entry))].matchAll(/^export import (\w+) =/gm)].map(match => match[1]);
  const text = banner + bodies.join('\n\n') + '\n\n' + publicNames.map(name => `export import ${name} = ${names.get(resolve(root, entry))}.${name};`).join('\n') + '\nexport {};\n';
  const typeInputs = program.getSourceFiles().map(s => portable(resolve(s.fileName)))
    .filter(path => path.startsWith('src/') || path.startsWith('node_modules/zod/'));
  return { text, inputs: typeInputs };
}

export function auditRuntimeGraph(metafile) {
  for (const [path, input] of Object.entries(metafile.inputs)) {
    if (!/^(src\/lib\/|src\/data\/|node_modules\/zod\/)/.test(path) && path !== 'supabase/functions/_shared/crypto.js') {
      throw new Error(`Forbidden runtime dependency: ${path}`);
    }
    for (const dependency of input.imports) {
      if (dependency.external) throw new Error(`External runtime dependency: ${dependency.path}`);
    }
  }
}

export function auditRuntimeSource(code) {
  const source = ts.createSourceFile('bundle.js', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const forbidden = new Set(['process', 'Deno', 'window', 'document', 'globalThis', 'fetch', 'XMLHttpRequest', 'WebSocket', 'require']);
  const visit = node => {
    if ((ts.isIdentifier(node) && forbidden.has(node.text)) || node.kind === ts.SyntaxKind.ImportKeyword) {
      throw new Error(`Environment access in calculation bundle: ${node.getText(source)}`);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}

export async function buildAgentLib({ write = true, overrides = {} } = {}) {
  const result = await build({ ...buildConfig, absWorkingDir: root, entryPoints: [entry], write: false, metafile: true,
    tsconfig: 'tsconfig.app.json', plugins: [{ name: 'test-inputs', setup(builder) {
      builder.onLoad({ filter: /\.(ts|json)$/ }, async args => {
        const replacement = overrides[portable(args.path)];
        return replacement === undefined ? undefined : { contents: replacement, loader: args.path.endsWith('.json') ? 'json' : 'ts' };
      });
    } }] });
  auditRuntimeGraph(result.metafile);
  auditRuntimeSource(result.outputFiles[0].text);
  const types = declarations(overrides);
  const inputs = [...new Set([...Object.keys(result.metafile.inputs), ...types.inputs, 'tsconfig.app.json',
    'scripts/build-agent-lib.mjs', 'scripts/check-agent-lib.mjs', 'docs/ai-assistant/cpu-policy.json', 'package.json', 'package-lock.json'])].sort();
  const inputHashes = {};
  for (const path of inputs) inputHashes[path] = hash(overrides[path] ?? await readFile(resolve(root, path), 'utf8'));
  inputHashes['build-config'] = hash(JSON.stringify({ buildConfig, declarationConfig: { ...declarationConfig, baseUrl: '.' }, esbuildVersion, typescriptVersion: ts.version }));
  const cnb = JSON.parse(overrides['src/data/cnbUsdCzk.json'] ?? await readFile(resolve(root, 'src/data/cnbUsdCzk.json'), 'utf8'));
  const rates = JSON.parse(overrides['src/data/cnbRates.json'] ?? await readFile(resolve(root, 'src/data/cnbRates.json'), 'utf8'));
  const cpuPolicy = JSON.parse(overrides['docs/ai-assistant/cpu-policy.json'] ?? await readFile(resolve(root, 'docs/ai-assistant/cpu-policy.json'), 'utf8'));
  const manifest = { schemaVersion: 1, calculationVersion: hash(JSON.stringify(inputHashes)), inputHashes,
    cnbThrough: [cnb.to, rates.to].sort()[0], cpuPolicy };
  const artifacts = { 'trackora-lib.js': '// @ts-self-types="./trackora-lib.d.ts"\n' + banner + result.outputFiles[0].text, 'trackora-lib.d.ts': types.text,
    'manifest.json': JSON.stringify(manifest, null, 2) + '\n' };
  if (write) {
    await mkdir(artifactDir, { recursive: true });
    for (const [name, text] of Object.entries(artifacts)) await writeFile(resolve(artifactDir, name), text);
  }
  return { manifest, metafile: result.metafile, artifacts };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const { manifest } = await buildAgentLib();
  console.info(`Built calculation bundle ${manifest.calculationVersion}; CNB through ${manifest.cnbThrough}`);
}
